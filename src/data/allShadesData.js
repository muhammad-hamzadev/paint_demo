// Dynamically generate up to 1000 Shades for complete 1000 shade library
const generate1000ColorShades = () => {
  const shades = [...baseShadesList];
  const colorFamilies = [
    { family: 'whites', familyName: 'Whites & Off-Whites', familyIcon: '⚪' },
    { family: 'beiges', familyName: 'Beiges & Sand', familyIcon: '🌾' },
    { family: 'blues', familyName: 'Blues & Navy', familyIcon: '🔵' },
    { family: 'greens', familyName: 'Greens & Sage', familyIcon: '🟢' },
    { family: 'grays', familyName: 'Grays & Slate', familyIcon: '🩶' },
    { family: 'reds', familyName: 'Reds & Terracotta', familyIcon: '🔴' },
    { family: 'yellows', familyName: 'Yellows & Gold', familyIcon: '🟡' },
    { family: 'purples', familyName: 'Purples & Lilac', familyIcon: '🪻' },
    { family: 'teals', familyName: 'Teals & Aquas', familyIcon: '🩵' },
    { family: 'earth', familyName: 'Earth Tones', familyIcon: '🟤' }
  ];

  const buckets = ['silk-touch', 'weather-shield', 'smooth-putty', 'aqueous-primer', 'royal-matt', 'card-only'];
  
  const adjectiveList = ['Royal', 'Velvet', 'Crystal', 'Luminous', 'Nordic', 'Vintage', 'Artisanal', 'Muted', 'Vibrant', 'Majestic', 'Soft', 'Deep', 'Radiant', 'Celestial', 'Imperial', 'Oceanic', 'Sunset', 'Alpine', 'Golden', 'Emerald', 'Sapphire', 'Pearl', 'Opal', 'Amber', 'Ruby', 'Topaz', 'Coral'];
  const nameList = ['Breeze', 'Mist', 'Glow', 'Shadow', 'Whisper', 'Reflection', 'Harmony', 'Elegance', 'Horizon', 'Dawn', 'Dusk', 'Serenade', 'Aura', 'Charm', 'Canvas', 'Velvet', 'Frost', 'Bloom', 'Serenity', 'Twilight', 'Solitude', 'Cascade', 'Zenith', 'Echo'];

  const hslToHex = (h, s, l) => {
    l /= 100;
    const a = (s * Math.min(l, 1 - l)) / 100;
    const f = (n) => {
      const k = (n + h / 30) % 12;
      const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
      return Math.round(255 * color).toString(16).padStart(2, '0');
    };
    return `#${f(0)}${f(8)}${f(4)}`.toUpperCase();
  };

  let count = shades.length + 1;
  while (count <= 1000) {
    const famObj = colorFamilies[count % colorFamilies.length];
    const adj = adjectiveList[count % adjectiveList.length];
    const nameWord = nameList[(count * 7) % nameList.length];
    const code = `ZIK-${String(count).padStart(4, '0')}`;
    
    const h = Math.round((count * 137.5) % 360);
    const s = 35 + (count % 50);
    const l = 30 + (count % 55);

    const hex = hslToHex(h, s, l);

    shades.push({
      code,
      name: `${adj} ${nameWord}`,
      family: famObj.family,
      familyName: famObj.familyName,
      familyIcon: famObj.familyIcon,
      hex,
      textLight: l < 50,
      bucket: buckets[count % buckets.length]
    });

    count++;
  }

  return shades;
};

